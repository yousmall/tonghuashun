"""页面与复核工作单共用的操作说明。"""
import streamlit as st


def render_review_guide() -> None:
    st.markdown("**交叉检验与人工复核：具体操作**")
    st.markdown(
        "1. **选择研究对象并刷新。** 进入「投资问答」，选择研究方向。行业分析可在「查询行业」选择或输入行业名称、板块代码，按回车确认，再点击「刷新数据」。已有对话时先展开「本页领域数据」。行业选择也用于多智能体协同；普通咨询时仍需写明行业名称。\n\n"
        "2. **发起完整分析。** 在底部「研究模式」选择「深度思考」，写明研究对象、时间范围与需要补查的指标后发送。等待完整回答生成；「3秒研究」主要用于查看已有资料概要。\n\n"
        "3. **查看自动核验结果。** 在最新回答下展开「分析过程与分项依据」，再展开「最后一步 · 交叉核验与风险检查」，查看观点核验、风险检查及具体分歧。结论下的「核验记录」列出部分资料缺口与待核实原因。自动核验随分析执行。\n\n"
        "4. **逐项对照原文。** 打开最新回答结论下的「交叉检验与人工复核工作单」，查看「本次待核实事项」和资料表，点击「查看原文」。核对对象与行业分类、板块代码、统计期、行情日期、数值单位以及结论是否有原文支持。没有链接时，自行查找原始发布材料并记录依据。缺失值不能按零处理，负市盈率不能直接解释为低估。\n\n"
        "5. **填写复核意见。** 完成核对后逐项勾选检查清单，填写「复核人」「核对的原文链接与统计口径」「逐项复核说明（含缺失项与分歧处理）」。证据不齐选择「仍待补证」；发现口径错误、数值冲突或依据不足选择「存在异议」；全部检查完成并有原文依据时，才选择「人工核对无异议」。\n\n"
        "6. **保存并下载。** 点击「保存本次复核记录」，再点击「下载人工复核记录」。记录仅保留在当前登录会话，退出前请下载 JSON 留存。\n\n"
        "7. **补查后重新核验。** 对仍缺失的指标，在底部继续选择「深度思考」，明确要求补查并重新分析。新回答生成后，重新查看核验状态、填写新工作单。复核表中的链接和说明用于留存人工依据，不会自动作为研究资料导入下一轮分析。"
    )
